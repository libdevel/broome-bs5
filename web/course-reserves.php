     <h1 class="page-header">Course Reserves</h1>

<p>
    Course reserves are books and videos set aside for use by a specific class. To make sure that these materials are available to all members of the class, the items are kept at the circulation desk and only circulate for a short period of time. &nbsp;You can <a href="https://suny-bcc.primo.exlibrisgroup.com/discovery/search?tab=CourseReserves&amp;search_scope=CourseReserves&amp;vid=01SUNY_BCC:01SUNY_BCC&amp;offset=0">search for materials on reserve in Primo</a>.
</p>
<p>
    &nbsp;
</p>
<h3>
    For Faculty
</h3>
<p>
    Course Reserves includes books – library books as well as instructors’ personal copies – photocopies of articles (within the current copyright guidelines), copies of past tests, answer keys, and course syllabi. You are welcome to submit reserve requests for etextbooks for your courses, though note that unfortunately many publishers do not offer ebook/etextbook licenses for libraries.
</p>
<p>
    The instructor placing materials on reserve is responsible for obtaining copyright permission.
</p>
<h3>
    Procedure
</h3>
<ol>
    <li>
        Review <a href="copyright-information-faculty.php">copyright information</a> regarding library reserve.
    </li>
    <li>
        Complete reserve form(s) for new items you are placing on reserve:
        <ol>
            <li>
                Form for hard copy (books and media) materials: <a href="files/reserve_form_print.pdf">Print Reserve Form</a>
            </li>
            <li>
                Request&nbsp;a textbook chapter scan for your Brightspace course:&nbsp;<a href="https://sunybroome.libwizard.com/f/scan">Form to Request a Chapter Scan</a>
            </li>
            <li>
                Form to renew reserve materials: <a href="files/reserve_renewal_form.pdf">Reserve renewal form</a>
            </li>
        </ol>
    </li>
    <li>
        At the end of each semester, do the following to remove or renew your course reserves:
        <ol>
            <li>
                Print out your renewal/removal list(s)
            </li>
            <li>
                Submit your renewal/removal list(s) to the library.
            </li>
        </ol>
    </li>
</ol>
<h3>
    Place a Reserve Purchase Request&nbsp;
</h3>
<p>
    If the Library does not own an item, you can place a request to purchase the item using the <a href="https://docs.google.com/forms/d/e/1FAIpQLSfcJufDFTWH-JbtN1pf_a5VPa6FyIHE7ibMFQBcp4IryNl2yA/viewform?usp=sf_link">Textbook Reserve Request Form</a>
</p>
<p>
    To request that the Library buy an item to add to the general collection (i.e. you will NOT place this item on reserve for your classes), please the <a href="purchase-request.php">purchase request form</a>.
</p>
<h3>
    Processing Time
</h3>
<ul>
    <li>
        Requests are processed in the order that they are submitted.
    </li>
    <li>
        If the item is in our collection, please allow up to one&nbsp;(1) week&nbsp;for processing.
    </li>
    <li>
        If the item is not in our collection, you may request that we purchase the item. Please note, it can take up to eight (8) weeks to process a new addition to the collection and place the item on reserve. (In some cases it can take longer depending on how difficult the item is to obtain.)
    </li>
</ul>
