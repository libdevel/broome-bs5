     <h1 class="page-header">Poster Printing Guidelines</h1>

        <h2>
    Description:
</h2>
<p>
    The library&nbsp;has a poster printing service with a large-format printer.&nbsp;&nbsp; The Epson plotter-printer can create posters for academic purposes in color or black and white.
</p>
<h2>
    How Do I Use This Service?:
</h2>
<p>
    To use the poster printer, please use our <a href="https://docs.google.com/a/sunybroome.edu/forms/d/e/1FAIpQLSfWv4zm7bfmF8yLIWKZ3tyuKWGJ1q4tiAaqPjCoT843ySngVA/viewform?entry.1704347683&amp;entry.2069726135&amp;entry.3868242&amp;entry.2075243722=Thanks!">large-format printing form</a> or ask your instructor to email/call the library.&nbsp; This service is limited to student projects for course purposes only, and must be authorized by a member of the faculty.&nbsp; You will need to include the course, name and email of the instructor who authorized the large-format printing on the form.&nbsp; Select a day and time from the available options and come to the library at that date with your file for printing.&nbsp; Templates for printing posters are available for download on the <a href="https://docs.google.com/a/sunybroome.edu/forms/d/e/1FAIpQLSfWv4zm7bfmF8yLIWKZ3tyuKWGJ1q4tiAaqPjCoT843ySngVA/viewform?entry.1704347683&amp;entry.2069726135&amp;entry.3868242&amp;entry.2075243722=Thanks!">large-format printing form</a>.&nbsp;&nbsp;
</p>
<h2>
    Who Can Use This Service?:
</h2>
<p>
    The large-format printer can only be used by students for course-related assignments.&nbsp; Faculty of the course must approve the use of the printer.&nbsp;
</p>
<h2>
    How Large Can The Plotter Print?
</h2>
<p>
    The maximum width of the plotter paper is 36 inches (size of the paper roll) but if orders are formatted in landscape mode, we can accommodate a variety of lengths, up to 56 inches.
</p>
<h2>
    Tips For Printing:
</h2>
<ul>
    <li>
        <strong>Best Quality Images</strong>: Your final file image should be 150-300dpi for the desired print dimensions.&nbsp; This will keep your image from looking pixelated (i.e., blurred).&nbsp; Any graphics/photos within your file image also should be 150-300dpi for the print dimensions.&nbsp; DPI means ‘dots per inch’, indicating the number of pixels in one inch.&nbsp; Please do not use DPI higher than 300 as it will not increase quality and will increase the time it takes to print the image.&nbsp; See the ‘addendum on image size’ below for more information.
    </li>
    <li>
        <strong>Fonts</strong>: All fonts that come with your operating system will embed in your images.&nbsp; However, if you are using a special font downloaded from the internet, you need to ensure that it will embed in your file.&nbsp; If you are not sure if your font has embedded, open the file on a computer that does not have the special font installed.&nbsp; If the image viewer has replaced the font with something else, it means the special font was not embedded in your file and the Library’s large format printer will not be able to print the font.
    </li>
    <li>
        <strong>Making a full-size poster with PowerPoint</strong>: Download and open one of our premade poster templates. Remember to delete any unused textboxes or their outline will show up in the poster.
    </li>
</ul>
