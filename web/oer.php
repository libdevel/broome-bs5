<h2>
    What are OER
</h2>
<p>
    Open Educational Resources (OER) can be any type of educational material - textbooks, assessments, syllabi, images, videos, presentations, etc. Anything that can be used in teaching, learning, and research can be considered an educational resource. Educational resources are considered open when they are available under an intellectual property license that allows for sharing, modification and reuse. Typically this means works covered under <a href="https://en.wikipedia.org/wiki/Creative_Commons_license">Creative Commons licenses</a> or works that reside in the <a href="https://fairuse.stanford.edu/overview/public-domain/">public domain</a>.&nbsp;The Library keeps a list of&nbsp;<a href="https://sunybroome.libguides.com/oer-collections">Open Educational Resources (OER) collections</a>&nbsp;which faculty can use to find OER.
</p>
<h2>
    Adopt an OER
</h2>
<p>
    If a faculty member agrees to adopt OER as the primary learning materials for their course, the SUNY Broome will provide a $500 award, made available through SUNY OER Funding. &nbsp;Apply for an <a href="oer-adoption-award.php">OER Adoption Award</a>.
</p>
<h2>
    Create an OER
</h2>
<p>
    If a faculty member agrees to create an OER as the primary learning materials for their course, the SUNY Broome will provide an award, made available through SUNY OER Funding. Apply for an <a href="oer-grant-program.php">OER Grant</a>.
</p>
<h2>
    Why use OER
</h2>
<h3>
    Save students money
</h3>
<p>
    Textbook prices have been <a href="https://www.aei.org/publication/chart-of-the-day-the-astronomical-rise-in-college-textbook-prices-vs-consumer-prices-and-recreational-books/">increasing at an alarming rate</a> for a long time now. This has a significant negative impact on student success. Using OER directly addresses this problem, thus improving student success, retention and persistence.
</p>
<h3>
    Improve access to education
</h3>
<p>
    In addition to making education more financially accessible, OER also give&nbsp;students access to course materials on the first day of class, which makes a significant contribution to student success.&nbsp;Also, most OER conform to ADA accessibility standards, something that can't be said of many commercial textbooks. The accessibility and affordability of OER serve to increase student success, retention and persistence.
</p>
<h3>
    Academic freedom
</h3>
<p>
    A textbook is always a compromise. Faculty look through the available options for works that are best align with learning outcomes and faculty and student needs.&nbsp;OER come with licenses to adapt, modify and reuse the resources, so they can be customized to suit personal pedagogical approaches and&nbsp;to meet the needs of specific student populations. Freedom from copyright restrictions opens up the kind of work faculty and students can do, allowing for more active pedagogies and creative projects.
</p>
<p>
    The Community College Consortium for Open Educational Resources (CCCOER) collects a number of case studies on how community colleges are leveraging OER: <a href="https://www.cccoer.org/case-studies/">OER Case Studies</a>&nbsp;
</p>
<p>
    The College Libraries of Ontario have an extensive&nbsp;online toolkit on OER and how to use them: <a href="https://tlp-lpa.ca/oer-toolkit/home">OER Toolkit</a>
</p>
<h2>
    Approaches for Using OER
</h2>
<ul>
    <li data-list-item-id="ec193a2e155eb309f5f79730145202929">
        Use / repurpose a pre-packaged course from an OER platform such as <a href="https://lumenlearning.com/">Lumen</a> or <a href="https://www.saylor.org/">Saylor Academy</a>. OER platforms can provide all the necessary low/no cost course materials, and many integrate directly with Blackboard.
    </li>
    <li data-list-item-id="e5c77558abc6bd6f815be93c6436454d9">
        Replace your textbook with an open one. The <a href="https://open.umn.edu/opentextbooks/">Open Textbook Library</a> is a great place to start – it has books from a number of open publishers (such as <a href="https://openstax.org/subjects">OpenStax</a>) along with reviews from teaching faculty.
    </li>
    <li data-list-item-id="e0cd3082b610a8ca4928d221ea3f4157e">
        Use a variety of open educational resources to meet your course objectives. Some examples would include chapters from OER textbooks, open lab software, Creative Commons or public domain multimedia, and more. The Library also has books, ebooks, articles, and multimedia databases (e.g. Kanopy, Naxos Music Library), which are freely available to students, faculty, and staff. Please consult with your librarian to find out what is possible.
    </li>
    <li data-list-item-id="e989c36880efd4da4684b31ac025e82cf">
        If there aren’t any OERs in the area you’re teaching, create some…
        <ol>
            <li data-list-item-id="e1e436c1722f4ec4e37fb19e7ac76759c">
                On your own (if you’re feeling ambitious)
            </li>
            <li data-list-item-id="e9d595df24b8484a318271bc923908902">
                With your colleagues (locally or outside of SUNY Broome)
            </li>
            <li data-list-item-id="ea273fb0e4d3572feb19bec0318c10af0">
                With your students
            </li>
        </ol>
    </li>
    <li data-list-item-id="ee9afd87d1da2d097a3f67c9a9d58edca">
        If you’re interested in building OER from existing open materials, or creating new OER, you should be aware of accessibility concerns. The <a href="https://open.ubc.ca/teach/oer-accessibility-toolkit/">OER Accessibility Toolkit</a> is a useful resource for understanding and evaluating accessibility.
    </li>
</ul>


